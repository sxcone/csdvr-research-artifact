def write_report(rows: list[dict[str, object]], summary: list[dict[str, object]], sensitivity: list[dict[str, object]]) -> None:
    cmp_methods = ["NoCheck", "FinalVerifier", "StepVerifier", "ReflectionRetry", "C-SDVR-NoRollback", "C-SDVR-NoSeverity"]
    lines = [
        "# C-SDVR v3 Executable Benchmark Statistical Report",
        "",
        "Verification Status: VERIFIED BY RE-RUNNABLE LOCAL CODE",
        "",
        "This report summarizes an executable-state benchmark. It is not a live LLM API or real-browser evaluation. Each run mutates an inspectable file-state or SQLite-backed web-form environment.",
        "",
        "## Primary Metrics",
        "",
        "| Method | Success | Detection F1 | Critical recall | Residue | Token cost | Unnecessary repair | Cost-normalized success |",
        "|---|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for r in summary:
        lines.append(
            f"| {r['method']} | {float(r['task_success_rate']):.3f} | {float(r['detection_f1']):.3f} | "
            f"{float(r['critical_recall']):.3f} | {float(r['side_effect_residue_rate']):.3f} | "
            f"{float(r['mean_token_cost']):.1f} | {float(r['unnecessary_repair_rate']):.3f} | {float(r['cost_norm_success']):.3f} |"
        )
    lines += [
        "",
        "## Bootstrap Paired Differences Against C-SDVR",
        "",
        "Positive success and cost-normalized differences mean C-SDVR is higher. Negative token differences mean C-SDVR is cheaper.",
        "",
        "| Comparator | Success diff | Cost-normalized diff | Token diff |",
        "|---|---:|---:|---:|",
    ]
    for comp in cmp_methods:
        s = bootstrap_diff(rows, "success", "C-SDVR", comp)
        c = bootstrap_diff(rows, "cost_norm_success", "C-SDVR", comp)
        t = bootstrap_diff(rows, "token_cost", "C-SDVR", comp)
        lines.append(f"| {comp} | {s[0]:.3f} [{s[1]:.3f}, {s[2]:.3f}] | {c[0]:.3f} [{c[1]:.3f}, {c[2]:.3f}] | {t[0]:.1f} [{t[1]:.1f}, {t[2]:.1f}] |")
    lines += [
        "",
        "## Sensitivity Analysis",
        "",
        "| Sensitivity factor | C-SDVR success | C-SDVR cost-normalized success | C-SDVR token cost |",
        "|---:|---:|---:|---:|",
    ]
    for r in sensitivity:
        if r["method"] == "C-SDVR":
            lines.append(
                f"| {float(r['sensitivity']):.2f} | {float(r['task_success_rate']):.3f} | "
                f"{float(r['cost_norm_success']):.3f} | {float(r['mean_token_cost']):.1f} |"
            )
    lines += [
        "",
        "## Statistical Fallacy Scan",
        "",
        "| Fallacy | Status | Note |",
        "|---|---|---|",
        "| Simulation-as-real-world fallacy | PASS | Manuscript must state this is an executable prototype benchmark, not live LLM/browser evaluation. |",
        "| Accuracy-only fallacy | PASS | Cost, latency, unnecessary repair, and residue are reported. |",
        "| Selective reporting | PASS | NoRollback and NoSeverity ablations are included. |",
        "| Parameter fragility | PARTIAL | Sensitivity factors are reported; future live-agent traces are still needed. |",
        "| External validity drift | WARN | File and form environments do not cover unrestricted web browsing or irreversible APIs. |",
        "| Multiple-comparison overclaim | PASS | Bootstrap intervals are descriptive; avoid formal superiority claims beyond this benchmark. |",
        "| Causal overclaim | PASS if preserved | Results compare policies under controlled executable traces, not deployed causal effects. |",
    ]
    REPORT_FILE.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    tasks = generate_tasks(120)
    task_rows = [t.__dict__ for t in tasks]
    write_csv(TASK_FILE, task_rows)

    rows = []
    for seed in range(50):
        for task in tasks:
            for method in METHODS:
                rows.append(run_one(task, method, seed))
    write_csv(RAW_FILE, rows)

    summary = summarize(rows, ["method"])
    summary.sort(key=lambda r: METHODS.index(r["method"]))
    write_csv(SUMMARY_FILE, summary)
    write_csv(DOMAIN_FILE, summarize(rows, ["method", "domain"]))
    write_csv(SEVERITY_FILE, summarize(rows, ["method", "severity"]))

    sens_rows = []
    for factor in [0.80, 0.90, 1.00, 1.10, 1.20]:
        sub = []
        for seed in range(15):
            for task in tasks:
                for method in ["C-SDVR-NoRollback", "C-SDVR-NoSeverity", "C-SDVR"]:
                    sub.append(run_one(task, method, seed, sensitivity=factor))
        sm = summarize(sub, ["method"])
        for r in sm:
            r["sensitivity"] = f"{factor:.2f}"
            sens_rows.append(r)
    write_csv(SENS_FILE, sens_rows)

    make_figures(summary)
    write_report(rows, summary, sens_rows)

    print(f"tasks={len(tasks)} methods={len(METHODS)} raw_runs={len(rows)}")
    print(f"outputs={OUT}")


if __name__ == "__main__":
    main()
