#!/usr/bin/env python3
"""Executable-state benchmark for C-SDVR.

This v3 experiment moves beyond the earlier trace-level pilot. It implements
two executable state environments:

1. A file-state environment with path/content/hash-level side effects.
2. A web-form environment backed by an in-memory SQLite record store.

The experiment is still not a live LLM API or real browser benchmark. Instead,
it evaluates recovery policies under paired executable side-effect traces
generated by a controlled fault-injection agent. Fault draws are shared across
policies for every task/seed pair, snapshots contain restorable state, and final
outcomes are checked against the intended state transition rather than a
destination-existence proxy.
"""

