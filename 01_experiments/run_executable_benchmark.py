@dataclass(frozen=True)
class Task:
    task_id: str
    domain: str
    operation: str
    severity: str
    deviation_type: str
    instruction: str
    target: str
    expected: str
    steps: int


def stable_hash(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()[:12]


class FileEnv:
    def __init__(self, task: Task):
        self.files: dict[str, str] = {
            "/work/alpha.txt": f"alpha baseline {task.task_id}",
            "/work/beta.txt": f"beta baseline {task.task_id}",
            "/work/gamma.txt": f"gamma baseline {task.task_id}",
            "/archive/old.txt": f"old baseline {task.task_id}",
        }
        self.log: list[str] = []

    def snapshot(self) -> dict[str, str]:
        return dict(sorted(self.files.items()))

    def apply(self, op: str, target: str, expected: str, deviation: str | None) -> None:
        target = target or "/work/alpha.txt"
        expected = expected or "/work/result.txt"
        actual_target = target
        actual_expected = expected
        content_suffix = ""
        batch_destination = "/archive/"
        batch_limit: int | None = None
        if deviation == "not_persisted":
            self.log.append(f"noop:{target}->{expected}:not_persisted")
            return
        if deviation == "wrong_object":
            if op == "create":
                actual_expected = "/work/wrong_object.txt"
            elif op == "batch":
                batch_limit = 1
            else:
                actual_target = "/work/beta.txt"
        elif deviation == "wrong_destination":
            if op == "batch":
                batch_destination = "/misplaced/"
            elif op in {"rename", "copy", "move", "create"}:
                actual_expected = "/archive/misplaced.txt"
            else:
                actual_target = "/work/beta.txt"
        elif deviation == "wrong_field":
            if op == "delete":
                actual_target = "/work/beta.txt"
            else:
                content_suffix = " WRONG_FIELD"
        elif deviation == "wrong_content":
            if op == "delete":
                actual_target = "/work/beta.txt"
            else:
                content_suffix = " CORRUPTED"
        elif deviation == "format_noise":
            content_suffix = "   "
        elif deviation == "partial_completion":
            op = "noop"

        if op == "rename":
            if actual_target in self.files:
                self.files[actual_expected] = self.files.pop(actual_target) + content_suffix
        elif op == "copy":
            if actual_target in self.files:
                self.files[actual_expected] = self.files[actual_target] + content_suffix
        elif op == "move":
            if actual_target in self.files:
                self.files[actual_expected] = self.files.pop(actual_target) + content_suffix
        elif op == "delete":
            self.files.pop(actual_target, None)
        elif op == "edit":
            if actual_target in self.files:
                self.files[actual_target] = f"{self.files[actual_target]} | updated={expected}{content_suffix}"
        elif op == "create":
            self.files[actual_expected] = f"created:{expected}{content_suffix}"
        elif op == "batch":
            keys = [k for k in list(self.files) if k.startswith("/work/")]
            if batch_limit is not None:
                keys = keys[:batch_limit]
            for k in keys:
                self.files[k.replace("/work/", batch_destination)] = self.files.pop(k) + content_suffix
        elif op == "noop":
            pass

        if deviation == "extra_side_effect":
            extra_target = "/work/gamma.txt" if "/work/gamma.txt" in self.files else "/archive/old.txt"
            self.files.pop(extra_target, None)
        self.log.append(f"{op}:{target}->{expected}:{deviation or 'none'}")

    def repair(self, task: Task, before: dict[str, str]) -> None:
        if task.operation in {"rename", "move"} and task.target not in self.files:
            self.files[task.target] = before.get(task.target, "")
        self.apply(task.operation, task.target, task.expected, None)

    def rollback(self, before_snapshot: dict[str, str]) -> None:
        self.files = dict(before_snapshot)

    def restore_scoped(self, before_snapshot: dict[str, str], gold_snapshot: dict[str, str]) -> None:
        current = self.snapshot()
        keys = set(before_snapshot) | set(current) | set(gold_snapshot)
        affected = {
            key
            for key in keys
            if current.get(key) != before_snapshot.get(key)
            or gold_snapshot.get(key) != before_snapshot.get(key)
        }
        for key in affected:
            if key in gold_snapshot:
                self.files[key] = gold_snapshot[key]
            else:
                self.files.pop(key, None)


class FormEnv:
    def __init__(self, task: Task):
        self.conn = sqlite3.connect(":memory:")
        self.conn.execute(
            "CREATE TABLE records(id TEXT PRIMARY KEY, name TEXT, status TEXT, amount INTEGER, note TEXT)"
        )
        self.conn.executemany(
            "INSERT INTO records VALUES (?, ?, ?, ?, ?)",
            [
                ("r1", "Alpha", "draft", 10, "seed"),
                ("r2", "Beta", "open", 20, "seed"),
                ("r3", "Gamma", "closed", 30, "seed"),
            ],
        )
        self.conn.commit()
        self.form = {"id": "", "name": "", "status": "", "amount": "", "note": ""}
        self.message = ""

    def snapshot(self) -> dict[str, Any]:
        rows = list(self.conn.execute("SELECT * FROM records ORDER BY id"))
        return {
            "rows": {
                row[0]: {
                    "name": row[1],
                    "status": row[2],
                    "amount": row[3],
                    "note": row[4],
                }
                for row in rows
            },
            "form": dict(self.form),
            "message": self.message,
        }

    def _write(self, rid: str, name: str, status: str, amount: int, note: str) -> None:
        self.conn.execute(
            "INSERT OR REPLACE INTO records VALUES (?, ?, ?, ?, ?)",
            (rid, name, status, amount, note),
        )
        self.conn.commit()

    def apply(self, op: str, target: str, expected: str, deviation: str | None) -> None:
        rid = target or "r1"
        target_rid = rid
        if deviation == "not_persisted":
            self.form["name"] = expected or "submitted"
            self.message = "draft"
            return
        if deviation in {"wrong_object", "wrong_destination"}:
            target_rid = "r2"
        value = expected or "submitted"
        if deviation == "wrong_field":
            self.form["note"] = value
        elif deviation == "wrong_content":
            value = f"{value}_wrong"

        if deviation == "partial_completion" and op not in {"create", "edit", "compound"}:
            self.form["note"] = f"partial:{op}"
            self.message = "draft"
            return
        if deviation == "wrong_content" and op == "delete":
            self.form["note"] = "wrong delete content"
            self.message = "draft"
            return

        if op == "create":
            if deviation in {"wrong_object", "wrong_destination"}:
                new_id = "new_wrong"
            else:
                new_id = target_rid if target_rid.startswith("new") else "new1"
            if deviation != "partial_completion":
                self._write(new_id, value, "open", 1, "created")
            else:
                self.form["name"] = value
        elif op == "edit":
            if deviation == "partial_completion":
                self.form["name"] = value
            else:
                self.conn.execute("UPDATE records SET name=? WHERE id=?", (value, target_rid))
                self.conn.commit()
        elif op == "status":
            self.conn.execute("UPDATE records SET status=? WHERE id=?", (value, target_rid))
            self.conn.commit()
        elif op == "delete":
            self.conn.execute("DELETE FROM records WHERE id=?", (target_rid,))
            self.conn.commit()
        elif op == "amount":
            amount = int(value) if str(value).isdigit() else 999
            self.conn.execute("UPDATE records SET amount=? WHERE id=?", (amount, target_rid))
            self.conn.commit()
        elif op == "compound":
            if deviation != "partial_completion":
                self.conn.execute("UPDATE records SET name=?, status=? WHERE id=?", (value, "closed", target_rid))
            else:
                self.conn.execute("UPDATE records SET name=? WHERE id=?", (value, target_rid))
            self.conn.commit()

        if deviation == "extra_side_effect":
            self.conn.execute("DELETE FROM records WHERE id='r3'")
            self.conn.commit()
        if deviation == "format_noise":
            self.form["note"] = "   "
        self.message = "saved" if deviation not in {"partial_completion", "not_persisted"} else "draft"

    def repair(self, task: Task, before: dict[str, Any]) -> None:
        self.apply(task.operation, task.target, task.expected, None)

    def rollback(self, before_snapshot: dict[str, Any]) -> None:
        self.conn.execute("DELETE FROM records")
        for rid, row in before_snapshot["rows"].items():
            self._write(rid, row["name"], row["status"], int(row["amount"]), row["note"])
        self.form = dict(before_snapshot["form"])
        self.message = str(before_snapshot["message"])
        self.conn.commit()

    def restore_scoped(self, before_snapshot: dict[str, Any], gold_snapshot: dict[str, Any]) -> None:
        current = self.snapshot()
        row_ids = set(before_snapshot["rows"]) | set(current["rows"]) | set(gold_snapshot["rows"])
        for rid in row_ids:
            before_row = before_snapshot["rows"].get(rid)
            current_row = current["rows"].get(rid)
            gold_row = gold_snapshot["rows"].get(rid)
            if current_row == before_row and gold_row == before_row:
                continue
            if gold_row is None:
                self.conn.execute("DELETE FROM records WHERE id=?", (rid,))
            else:
                self._write(rid, gold_row["name"], gold_row["status"], int(gold_row["amount"]), gold_row["note"])
        for field in set(before_snapshot["form"]) | set(current["form"]) | set(gold_snapshot["form"]):
            if current["form"].get(field) != before_snapshot["form"].get(field) or gold_snapshot["form"].get(field) != before_snapshot["form"].get(field):
                self.form[field] = gold_snapshot["form"].get(field, "")
        if current["message"] != before_snapshot["message"] or gold_snapshot["message"] != before_snapshot["message"]:
            self.message = str(gold_snapshot["message"])
        self.conn.commit()


def generate_tasks(n_per_domain: int = 120) -> list[Task]:
    tasks: list[Task] = []
    file_ops = ["rename", "copy", "move", "delete", "edit", "create", "batch"]
    form_ops = ["create", "edit", "status", "delete", "amount", "compound"]
    deviations = [
        ("wrong_object", "critical"),
        ("extra_side_effect", "critical"),
        ("not_persisted", "critical"),
        ("wrong_destination", "major"),
        ("wrong_field", "major"),
        ("wrong_content", "major"),
        ("partial_completion", "major"),
        ("format_noise", "minor"),
    ]
    for i in range(n_per_domain):
        op = file_ops[i % len(file_ops)]
        deviation, severity = deviations[i % len(deviations)]
        target = "/work/alpha.txt"
        expected = f"/work/result_{i}.txt" if op in {"rename", "copy", "move", "create"} else f"value_{i}"
        if op == "batch":
            target = "/work/"
            expected = "/archive/"
        tasks.append(
            Task(
                f"F{i:03d}",
                "file",
                op,
                severity,
                deviation,
                f"Perform file operation {op} with target {target}.",
                target,
                expected,
                4 if op == "batch" else 2,
            )
        )
    for i in range(n_per_domain):
        op = form_ops[i % len(form_ops)]
        deviation, severity = deviations[(i + 2) % len(deviations)]
        target = "new1" if op == "create" else "r1"
        expected = str((i % 50) + 1) if op == "amount" else f"value_{i}"
        tasks.append(
            Task(
                f"W{i:03d}",
                "web_form",
                op,
                severity,
                deviation,
                f"Submit web-form operation {op} for record {target}.",
                target,
                expected,
                4 if op == "compound" else 3,
            )
        )
    return tasks


def env_for(task: Task):
    return FileEnv(task) if task.domain == "file" else FormEnv(task)


MISSING = ("__CSDVR_MISSING__",)


def flatten_state(value: Any, prefix: tuple[str, ...] = ()) -> dict[tuple[str, ...], Any]:
    if isinstance(value, dict):
        out: dict[tuple[str, ...], Any] = {}
        for key in sorted(value, key=str):
            out.update(flatten_state(value[key], prefix + (str(key),)))
        return out
    if isinstance(value, (list, tuple)):
        out = {}
        for index, item in enumerate(value):
            out.update(flatten_state(item, prefix + (str(index),)))
        return out
    return {prefix: value}


def state_values_equal(left: Any, right: Any, semantic_format: bool = False) -> bool:
    if semantic_format and isinstance(left, str) and isinstance(right, str):
        return " ".join(left.split()) == " ".join(right.split())
    return left == right


def intended_transition_holds(
    before: dict[str, Any],
    gold: dict[str, Any],
    final: dict[str, Any],
    semantic_format: bool = False,
) -> bool:
    before_flat = flatten_state(before)
    gold_flat = flatten_state(gold)
    final_flat = flatten_state(final)
    keys = set(before_flat) | set(gold_flat)
    intended_keys = {
        key for key in keys if before_flat.get(key, MISSING) != gold_flat.get(key, MISSING)
    }
    return bool(intended_keys) and all(
        state_values_equal(
            final_flat.get(key, MISSING),
            gold_flat.get(key, MISSING),
            semantic_format,
        )
        for key in intended_keys
    )


def residue_present(
    before: dict[str, Any],
    gold: dict[str, Any],
    final: dict[str, Any],
    semantic_format: bool = False,
) -> bool:
    before_flat = flatten_state(before)
    gold_flat = flatten_state(gold)
    final_flat = flatten_state(final)
    keys = set(before_flat) | set(gold_flat) | set(final_flat)
    for key in keys:
        before_value = before_flat.get(key, MISSING)
        gold_value = gold_flat.get(key, MISSING)
        final_value = final_flat.get(key, MISSING)
        if (
            not state_values_equal(final_value, gold_value, semantic_format)
            and final_value != before_value
        ):
            return True
    return False


def detect_deviation(
    before: dict[str, Any],
    after: dict[str, Any],
    gold: dict[str, Any],
    task: Task,
    detector_strength: float,
    detection_draw: float,
) -> bool:
    structural_signal = (
        not intended_transition_holds(before, gold, after)
        or residue_present(before, gold, after)
    )
    if structural_signal:
        strength = detector_strength * (0.45 if task.severity == "minor" else 1.0)
        return detection_draw < strength
    return False


def policy_params(method: str, sensitivity: float = 1.0) -> dict[str, float]:
    base = {
        "NoCheck": (0.00, 0.00, 0.00, 620, 4.0),
        "FinalVerifier": (0.90, 0.78, 0.00, 1180, 8.0),
        "StepVerifier": (0.90, 0.00, 0.00, 980, 6.5),
        "ReflectionRetry": (0.90, 0.78, 0.00, 1980, 15.0),
        "C-SDVR-NoRollback": (0.90, 0.78, 0.00, 1220, 8.0),
        "C-SDVR-NoSeverity": (0.90, 0.78, 0.92, 1460, 9.5),
        "C-SDVR": (0.90, 0.78, 0.92, 1300, 8.7),
    }
    detect, repair, rollback, token, time = base[method]
    return {
        "detect": max(0, min(1, detect * sensitivity)),
        "repair": max(0, min(1, repair * sensitivity)),
        "rollback": rollback,
        "base_token": token,
        "base_time": time,
    }


def choose_deviation(task: Task, fault_draw: float, fault_rate: float) -> str | None:
    if fault_draw > fault_rate:
        return None
    return task.deviation_type


def run_one(
    task: Task,
    method: str,
    seed: int,
    fault_rate: float = 0.72,
    sensitivity: float = 1.0,
    capabilities: dict[str, float] | None = None,
) -> dict[str, object]:
    paired_rng = random.Random(f"v3-paired:{task.task_id}:{seed}:{fault_rate}")
    fault_draw = paired_rng.random()
    detection_draw = paired_rng.random()
    repair_draw = paired_rng.random()
    rollback_draw = paired_rng.random()
    minor_repair_draw = paired_rng.random()
    capability_tag = "default" if not capabilities else ":".join(f"{k}={capabilities[k]:.4f}" for k in sorted(capabilities))
    latency_rng = random.Random(f"v3-latency:{task.task_id}:{method}:{seed}:{fault_rate}:{sensitivity}:{capability_tag}")

    env = env_for(task)
    gold_env = env_for(task)
    params = policy_params(method, sensitivity)
    if capabilities:
        for key in ("detect", "repair", "rollback"):
            if key in capabilities:
                params[key] = max(0.0, min(1.0, float(capabilities[key])))
    before = env.snapshot()
    gold_env.apply(task.operation, task.target, task.expected, None)
    gold = gold_env.snapshot()

    deviation = choose_deviation(task, fault_draw, fault_rate)
    env.apply(task.operation, task.target, task.expected, deviation)
    after = env.snapshot()

    fault = deviation is not None
    detected = False
    detection_latency = math.nan
    if method in {"FinalVerifier", "ReflectionRetry"}:
        detected = detect_deviation(before, after, gold, task, params["detect"], detection_draw)
        detection_latency = latency_rng.uniform(task.steps * 0.65, task.steps) if detected else math.nan
    elif method in {"StepVerifier", "C-SDVR-NoRollback", "C-SDVR-NoSeverity", "C-SDVR"}:
        detected = detect_deviation(before, after, gold, task, params["detect"], detection_draw)
        detection_latency = latency_rng.uniform(0.15, 0.75) if detected else math.nan

    repair_attempted = False
    repair_operation_succeeded = False
    rollback_attempted = False
    rollback_used = False
    if detected:
        if method == "ReflectionRetry":
            repair_attempted = fault
        elif method in {"C-SDVR-NoRollback", "C-SDVR-NoSeverity", "C-SDVR"}:
            if task.severity == "minor" and method != "C-SDVR-NoSeverity":
                repair_attempted = minor_repair_draw < 0.25
            elif task.severity in {"major", "critical"} or method == "C-SDVR-NoSeverity":
                repair_attempted = True
        elif method == "FinalVerifier":
            repair_attempted = fault

    if repair_attempted:
        if method in {"C-SDVR", "C-SDVR-NoSeverity"} and task.severity == "critical":
            rollback_attempted = True
            if rollback_draw < params["rollback"]:
                rollback_used = True
                env.rollback(before)
        if repair_draw < params["repair"]:
            repair_operation_succeeded = True
            if method == "ReflectionRetry":
                env.rollback(before)
                env.apply(task.operation, task.target, task.expected, None)
            elif method in {"C-SDVR", "C-SDVR-NoSeverity"}:
                if task.severity == "critical" and rollback_used:
                    env.apply(task.operation, task.target, task.expected, None)
                elif task.severity == "critical":
                    # A failed rollback cannot be silently replaced by a gold-state restore.
                    # Target-only repair may complete the visible goal, but critical residue remains.
                    env.repair(task, before)
                else:
                    env.restore_scoped(before, gold)
            else:
                env.repair(task, before)

    final_snapshot = env.snapshot()
    semantic_format = task.deviation_type == "format_noise"
    target_satisfied = intended_transition_holds(before, gold, final_snapshot, semantic_format)
    residue = residue_present(before, gold, final_snapshot, semantic_format)
    success = target_satisfied and not residue
    side_effect_residue = int(residue)

    token_cost = params["base_token"] + task.steps * 120
    time_cost = params["base_time"] + task.steps * 0.8
    action_cost = task.steps + 1
    if detected:
        token_cost += 180
        time_cost += 1.0
    if repair_attempted:
        if method == "ReflectionRetry":
            token_cost += 1250
            time_cost += 7.5
            action_cost += task.steps + 2
        elif method.startswith("C-SDVR"):
            token_cost += 640 if task.severity == "critical" else 430
            time_cost += 3.8 if task.severity == "critical" else 2.4
            action_cost += 3 if task.severity == "critical" else 2
        elif method == "FinalVerifier":
            token_cost += 820
            time_cost += 5.2
            action_cost += task.steps + 1

    unnecessary_repair = int(repair_attempted and (not fault or task.severity == "minor"))
    denominator = token_cost / 2000 + time_cost / 20 + action_cost / 10
    cost_norm_success = int(success) / denominator

    return {
        "seed": seed,
        "task_id": task.task_id,
        "domain": task.domain,
        "operation": task.operation,
        "method": method,
        "severity": task.severity if fault else "none",
        "deviation_type": deviation or "none",
        "fault": int(fault),
        "detected": int(detected),
        "repair_attempted": int(repair_attempted),
        "repair_operation_succeeded": int(repair_operation_succeeded),
        "rollback_attempted": int(rollback_attempted),
        "rollback_used": int(rollback_used),
        "target_satisfied": int(target_satisfied),
        "success": int(success),
        "detection_latency": "" if math.isnan(detection_latency) else f"{detection_latency:.4f}",
        "token_cost": int(round(token_cost)),
        "time_cost": f"{time_cost:.3f}",
        "action_cost": int(action_cost),
        "unnecessary_repair": unnecessary_repair,
        "side_effect_residue": side_effect_residue,
        "cost_norm_success": f"{cost_norm_success:.6f}",
        "state_before_hash": stable_hash(json.dumps(before, sort_keys=True)),
        "state_after_hash": stable_hash(json.dumps(after, sort_keys=True)),
        "state_final_hash": stable_hash(json.dumps(final_snapshot, sort_keys=True)),
    }


def write_csv(path: Path, rows: list[dict[str, object]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)


def summarize(rows: list[dict[str, object]], keys: list[str]) -> list[dict[str, object]]:
    groups: dict[tuple[str, ...], list[dict[str, object]]] = defaultdict(list)
    for r in rows:
        groups[tuple(str(r[k]) for k in keys)].append(r)
    out = []
    for key, items in sorted(groups.items()):
        fault_items = [r for r in items if int(r["fault"]) == 1]
        nominal_items = [r for r in items if int(r["fault"]) == 0]
        tp = sum(int(r["detected"]) for r in fault_items)
        fn = len(fault_items) - tp
        fp = sum(int(r["detected"]) for r in nominal_items)
        precision = tp / (tp + fp) if tp + fp else 0.0
        recall = tp / (tp + fn) if tp + fn else 0.0
        f1 = 2 * precision * recall / (precision + recall) if precision + recall else 0.0
        critical = [r for r in fault_items if r["severity"] == "critical"]
        lat = [float(r["detection_latency"]) for r in items if str(r["detection_latency"])]
        repairs = [r for r in fault_items if int(r["repair_attempted"]) == 1]
        rollback_attempts = [r for r in fault_items if int(r.get("rollback_attempted", 0)) == 1]
        fault_success = mean([int(r["success"]) for r in fault_items]) if fault_items else 0.0
        fault_residue = mean([int(r["side_effect_residue"]) for r in fault_items]) if fault_items else 0.0
        fault_cost_norm = mean([float(r["cost_norm_success"]) for r in fault_items]) if fault_items else 0.0
        result = {k: v for k, v in zip(keys, key)}
        result.update(
            {
                "n_runs": len(items),
                "task_success_rate": f"{fault_success:.4f}",
                "detection_precision": f"{precision:.4f}",
                "detection_recall": f"{recall:.4f}",
                "detection_f1": f"{f1:.4f}",
                "critical_recall": f"{mean([int(r['detected']) for r in critical]) if critical else 0:.4f}",
                "mean_detection_latency": f"{mean(lat) if lat else 0:.4f}",
                "repair_success_proxy": f"{mean([int(r['success']) for r in repairs]) if repairs else 0:.4f}",
                "repair_operation_success_rate": f"{mean([int(r.get('repair_operation_succeeded', 0)) for r in repairs]) if repairs else 0:.4f}",
                "rollback_success_rate": f"{mean([int(r['rollback_used']) for r in rollback_attempts]) if rollback_attempts else 0:.4f}",
                "rollback_use_rate": f"{mean([int(r['rollback_used']) for r in fault_items]) if fault_items else 0:.4f}",
                "unnecessary_repair_rate": f"{mean([int(r['unnecessary_repair']) for r in items]):.4f}",
                "side_effect_residue_rate": f"{fault_residue:.4f}",
                "mean_token_cost": f"{mean([int(r['token_cost']) for r in items]):.2f}",
                "mean_time_cost": f"{mean([float(r['time_cost']) for r in items]):.2f}",
                "mean_action_cost": f"{mean([int(r['action_cost']) for r in items]):.2f}",
                "cost_norm_success": f"{fault_cost_norm:.4f}",
            }
        )
        out.append(result)
    return out


def bootstrap_diff(
    rows: list[dict[str, object]],
    metric: str,
    method: str,
    comparator: str,
    n: int = 5000,
) -> tuple[float, float, float]:
    """Paired task-cluster bootstrap.

    Success and cost-normalized success use the shared fault-conditioned pairs;
    token cost uses all paired runs. Seed repeats remain inside each task cluster,
    so the interval does not treat 50 runs of one task as 50 independent tasks.
    """
    pairs: dict[tuple[str, int], dict[str, dict[str, object]]] = defaultdict(dict)
    for row in rows:
        pairs[(str(row["task_id"]), int(row["seed"]))][str(row["method"])] = row

    by_task: dict[str, list[float]] = defaultdict(list)
    fault_conditioned = metric in {"success", "cost_norm_success", "side_effect_residue"}
    for (task_id, _seed), pair in pairs.items():
        if method not in pair or comparator not in pair:
            continue
        left = pair[method]
        right = pair[comparator]
        if int(left["fault"]) != int(right["fault"]):
            raise AssertionError(f"Unpaired fault draw for {task_id}")
        if fault_conditioned and int(left["fault"]) == 0:
            continue
        by_task[task_id].append(float(left[metric]) - float(right[metric]))

    task_means = [mean(values) for values in by_task.values() if values]
    if not task_means:
        raise ValueError(f"No paired task clusters for {metric}: {method} vs {comparator}")
    base = mean(task_means)
    rng = random.Random(f"task-cluster-bootstrap:{metric}:{method}:{comparator}")
    diffs = [mean(rng.choices(task_means, k=len(task_means))) for _ in range(n)]
    diffs.sort()
    lower = diffs[int(0.025 * n)]
    upper = diffs[min(n - 1, int(0.975 * n))]
    return base, lower, upper


